#!/usr/bin/env python3
"""Generate the members the WinUI XAML compiler would produce, so the C# in Radha.App can be
type-checked on any OS (the XAML compiler itself is a Windows-only executable).

For every .xaml with an x:Class we emit `InitializeComponent()` plus one field per x:Name,
typed from the element in the markup. This is NOT a XAML compiler: it only satisfies the
compiler for member resolution; layout/binding correctness is covered by tools/XamlAudit.
"""
import re, sys, pathlib
import xml.etree.ElementTree as ET

XAML_NS = "{http://schemas.microsoft.com/winfx/2006/xaml}"

SIMPLE = {
    "Grid": "Microsoft.UI.Xaml.Controls.Grid",
    "StackPanel": "Microsoft.UI.Xaml.Controls.StackPanel",
    "Button": "Microsoft.UI.Xaml.Controls.Button",
    "TextBlock": "Microsoft.UI.Xaml.Controls.TextBlock",
    "Border": "Microsoft.UI.Xaml.Controls.Border",
    "ProgressBar": "Microsoft.UI.Xaml.Controls.ProgressBar",
    "TextBox": "Microsoft.UI.Xaml.Controls.TextBox",
    "Pivot": "Microsoft.UI.Xaml.Controls.Pivot",
    "ListView": "Microsoft.UI.Xaml.Controls.ListView",
    "Slider": "Microsoft.UI.Xaml.Controls.Slider",
    "ComboBox": "Microsoft.UI.Xaml.Controls.ComboBox",
    "FontIcon": "Microsoft.UI.Xaml.Controls.FontIcon",
    "ItemsControl": "Microsoft.UI.Xaml.Controls.ItemsControl",
    "ItemsRepeater": "Microsoft.UI.Xaml.Controls.ItemsRepeater",
    "UserControl": "Microsoft.UI.Xaml.Controls.UserControl",
}

def type_for(el, prefixes):
    tag = el.tag
    if not tag.startswith("{"):
        return None
    ns, local = tag[1:].split("}")
    if local in SIMPLE:
        return SIMPLE[local]
    # prefixed element (views:, controls:)
    for prefix, clr in prefixes.items():
        if ns == f"using:{clr}":
            return f"{clr}.{local}"
    return f"Microsoft.UI.Xaml.FrameworkElement"

def main(root, out):
    app = pathlib.Path(root) / "src" / "Radha.App"
    out = pathlib.Path(out); out.mkdir(parents=True, exist_ok=True)
    count = 0
    for xaml in sorted(app.rglob("*.xaml")):
        try:
            doc = ET.parse(xaml)
        except ET.ParseError as e:
            print(f"skip {xaml}: {e}", file=sys.stderr); continue
        r = doc.getroot()
        cls = r.get(f"{XAML_NS}Class")
        if not cls:
            continue  # ResourceDictionary / merged dictionaries
        prefixes = {}
        for k, v in r.attrib.items():
            if k.startswith("{http://www.w3.org/2000/xmlns/}") or (k.startswith("xmlns:")):
                prefix = k.split("}")[-1].split(":")[-1]
                if v.startswith("using:"):
                    prefixes[prefix] = v[6:]
        fields = []
        seen = set()
        for el in r.iter():
            name = el.get(f"{XAML_NS}Name")
            if not name or name in seen:
                continue
            seen.add(name)
            t = type_for(el, prefixes) or "Microsoft.UI.Xaml.FrameworkElement"
            fields.append((t, name))
        ns, name = cls.rsplit(".", 1)
        lines = ["// <auto-generated> stub for type-checking only (see tools/TypeCheck)</auto-generated>",
                 "#nullable disable",
                 f"namespace {ns}",
                 "{",
                 f"    public partial class {name}",
                 "    {",
                 "        private void InitializeComponent() { }"]
        for t, n in fields:
            lines.append(f"        private global::{t} {n};")
        lines += ["    }", "}"]
        (out / f"{name}.g.cs").write_text("\n".join(lines) + "\n")
        count += 1
        print(f"  stub {cls}: {len(fields)} named element(s)")
    print(f"generated {count} stub file(s) in {out}")

if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else ".", sys.argv[2] if len(sys.argv) > 2 else "obj/typecheck")
